export const getPaginatedBlogs = (page = 1, pageSize = 9) => {
  const start = (page - 1) * pageSize;
  const end = start + pageSize;
  const paginatedData = blogData.slice(start, end);
  
  return {
    data: paginatedData,
    meta: {
      pagination: {
        page,
        pageSize,
        pageCount: Math.ceil(blogData.length / pageSize),
        total: blogData.length
      }
    }
  };
};

